#!/usr/bin/env python3
"""
verify_accents_banks.py -- OFFLINE verification of the per-bank accent
material (WS1), without running the game.

It emulates exactly what `mod/recomp/accents_es.h` does:

  1. loads `translation/accents_atlas.bin` (IUA1 format);
  2. for each bank, takes the ORIGINAL AIF (`extract/f0/<stem>.aif`), locates the
     atlas as `msgbase - aif_size` (here, simply the AIF itself) and writes
     the 16 DXT blocks of each glyph into the indicated cells with the same
     Xbox 360 tiled addressing;
  3. checks that the result is IDENTICAL byte for byte to the `<stem>_accents.aif`
     generated by `tools/add_accents_banks.py`;
  4. patches the `.msg` metric table (metric of the base cell) and
     compares it with `<stem>_accents.msg`;
  5. validates the signature: the FNV-64 of the original AIF matches the bin's;
  6. game codec round-trip for a test string per bank: the accent
     codes must resolve to the NEW glyph (not to `?`).

Usage
-----
    python -X utf8 tools/verify_accents_banks.py
    python -X utf8 tools/verify_accents_banks.py --png out_dir
"""

from __future__ import annotations

import argparse
import json
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(REPO / "tools" / "vendor" / "pc-infiniteundiscovery" / "tools"))

import aif as aif_mod          # noqa: E402
import aif_edit                # noqa: E402
import game_text_codec as codec  # noqa: E402
from PIL import Image          # noqa: E402

CELL = 32
RT_MAGIC = 0x31415549


def fnv64(data: bytes) -> int:
    h = 1469598103934665603
    for b in data:
        h ^= b
        h = (h * 1099511628211) & 0xFFFFFFFFFFFFFFFF
    return h


def load_bin(path: Path):
    raw = path.read_bytes()
    magic, n = struct.unpack_from("<II", raw, 0)
    assert magic == RT_MAGIC, "magic IUA1 incorrecto"
    off = 8
    banks = []
    for _ in range(n):
        h = struct.unpack_from("<IIIIIIIIIIII", raw, off); off += 48
        fnv = struct.unpack_from("<Q", raw, off)[0]; off += 8
        ng = struct.unpack_from("<I", raw, off)[0]; off += 4
        glyphs = []
        for _g in range(ng):
            cell, bc, metric, pad = struct.unpack_from("<HHHH", raw, off); off += 8
            blocks = raw[off:off + 1024]; off += 1024
            glyphs.append({"cell": cell, "base_cell": bc, "metric": metric,
                           "blocks": blocks})
        banks.append({"hdr": h, "fnv": fnv, "glyphs": glyphs})
    return banks


def patch_aif_like_hook(aif_bytes: bytes, bank: dict) -> bytes:
    """Emulates the hook's PatchAtlas over the original AIF bytes."""
    (aif_len, width, height, fmt, ident, tw, pixels_off, eb,
     total, count, aw, ah) = bank["hdr"]
    assert len(aif_bytes) == aif_len
    buf = bytearray(aif_bytes)
    cols = aw // 32
    for g in bank["glyphs"]:
        row, col = divmod(g["cell"], cols)
        bi = 0
        for gy in range(8):
            for gx in range(8):
                off = aif_mod.tiled_offset(col * 8 + gx, row * 8 + gy, tw, eb) * eb
                buf[pixels_off + off:pixels_off + off + eb] = g["blocks"][bi:bi + eb]
                bi += eb
    return bytes(buf)


def patch_msg_like_hook(msg_bytes: bytes, bank: dict) -> bytes:
    """Emulates the hook's PatchMetrics over the original .msg bytes."""
    buf = bytearray(msg_bytes)
    mo = struct.unpack_from(">I", buf, 0x28)[0]
    for g in bank["glyphs"]:
        metric = g["metric"]
        if g["base_cell"] != 0xFFFF:
            boff = mo + 2 * g["base_cell"]
            if boff + 2 <= len(buf):
                metric = struct.unpack_from(">H", buf, boff)[0]
        off = mo + 2 * g["cell"]
        if off + 2 <= len(buf):
            struct.pack_into(">H", buf, off, metric)
    return bytes(buf)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--bin", default=str(REPO / "mod" / "translation" / "accents_atlas.bin"))
    ap.add_argument("--manifest", default=str(REPO / "mod" / "translation" / "accents_manifest.json"))
    ap.add_argument("--f0", default=str(REPO / "extract" / "f0"))
    ap.add_argument("--accents", default=str(REPO / "extract" / "f2" / "accents"))
    ap.add_argument("--png", default=None, help="directorio para montajes de prueba")
    args = ap.parse_args(argv)

    banks = load_bin(Path(args.bin))
    man = json.loads(Path(args.manifest).read_text(encoding="utf-8"))["bancos"]
    man_by_stem = {b["stem"]: b for b in man}
    print("bin: %d bancos; manifiesto: %d bancos" % (len(banks), len(man)))

    ok_all = True
    for i, bank in enumerate(banks):
        m = man[i]
        stem = m["stem"]
        aif0 = (Path(args.f0) / (stem + ".aif")).read_bytes()
        msg0 = (Path(args.f0) / (stem + ".msg")).read_bytes()

        # 1) signature
        if fnv64(aif0) != bank["fnv"]:
            print("  [x] %s: FNV del AIF no coincide" % stem); ok_all = False; continue

        # 2) atlas: hook vs generated file
        patched = patch_aif_like_hook(aif0, bank)
        want = (Path(args.accents) / (stem + "_accents.aif"))
        if not want.is_file():
            print("  [x] %s: falta %s" % (stem, want.name)); ok_all = False; continue
        same_aif = patched == want.read_bytes()
        if not same_aif:
            print("  [x] %s: el parche del hook != %s" % (stem, want.name)); ok_all = False

        # 3) metrics
        pmsg = patch_msg_like_hook(msg0, bank)
        wmsg = (Path(args.accents) / (stem + "_accents.msg"))
        same_msg = wmsg.is_file() and pmsg == wmsg.read_bytes()
        if not same_msg:
            print("  [x] %s: las metricas del hook != %s" % (stem, wmsg.name)); ok_all = False

        # 4) render: the glyphs must have ink and not just be the rotated '?'
        w, h, rgba = aif_edit.decode_rgba(patched)
        cols = w // 32
        src = Image.frombytes("RGBA", (w, h), rgba)
        ink_ok = True
        for g in m["glyphs"]:
            r, c = divmod(g["cell"], cols)
            cell = src.crop((c * 32, r * 32, c * 32 + 32, r * 32 + 32))
            bb = cell.split()[3].getbbox()
            if not bb:
                ink_ok = False
                print("  [x] %s: celda %d (%s) vacia" % (stem, g["cell"], g["char"]))
        if not ink_ok:
            ok_all = False

        # 5) codec round-trip with a test string
        codes = [g["code"] for g in m["glyphs"]]
        blob = codec.encode(codes)
        back = codec.decode(blob)
        rt = back == codes

        print("  [%s] %-28s glifos=%2d aif=%s msg=%s rt=%s reutiliza=%s" % (
            "ok" if (same_aif and same_msg and rt and ink_ok) else "x",
            stem, len(m["glyphs"]), "=" if same_aif else "!",
            "=" if same_msg else "!", "ok" if rt else "FALLO",
            m.get("missing_bases")))

        if args.png:
            out = Path(args.png)
            out.mkdir(parents=True, exist_ok=True)
            S = 3
            n = len(m["glyphs"])
            canvas = Image.new("RGBA", (n * (32 * S + 4) + 8, 32 * S + 36), (18, 18, 22, 255))
            from PIL import ImageDraw
            dr = ImageDraw.Draw(canvas)
            for j, g in enumerate(m["glyphs"]):
                r, c = divmod(g["cell"], cols)
                cell = src.crop((c * 32, r * 32, c * 32 + 32, r * 32 + 32)) \
                          .resize((32 * S, 32 * S), Image.NEAREST)
                x = 4 + j * (32 * S + 4)
                canvas.alpha_composite(cell, (x, 2))
                dr.text((x + 1, 32 * S + 4), "%s=%d" % (g["char"], g["code"]),
                        fill=(255, 255, 0, 255))
            canvas.save(out / (stem + "_verify.png"))

    print("\nRESULTADO:", "TODO OK" if ok_all else "HAY FALLOS")
    return 0 if ok_all else 1


if __name__ == "__main__":
    raise SystemExit(main())

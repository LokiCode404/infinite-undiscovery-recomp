#!/usr/bin/env python3
"""
build_es_codes.py -- translation -> game codes -> binary catalog, WITH REFLOW.

Reads `translation/es.json` ({"strings":[{stem,id,es},...]}) and the per-bank
charmaps (`translation/charmaps/<stem>.json`, schema code->character, UTF-8)
and produces:

  * `translation/es_codes.json`   { stem: { id: [codes] } }
  * `translation/es_catalog.bin`  (via tools/gen_es_catalog.py)

UI RULES (anti-overflow):
  * 0x4000 = line break;  the space is a normal glyph.
  * advance of a glyph = LOW byte of its metric (table at metrics_off, 2 B/glyph).
  * REFLOW is done: each line of the translation must have
        Sum(advance) <= Target
    where Target = max Sum(advance) of the ORIGINAL's lines.
  * the number of lines of the translation must not exceed the original's.

Characters without a glyph are reported (and `--fold` replaces them with ASCII equivalents).
"""

from __future__ import annotations

import argparse
import json
import struct
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "tools"))
import gen_es_catalog as gen  # noqa: E402
from decode_messages import MsgBank  # noqa: E402

LINE_BREAK = 0x4000
# controls that break the line (menu: 0x4000; dialogue: 0x4000/0x4005)
BREAKS = (0x4000, 0x4005)
# str->str dict (NOT str.maketrans: its keys are ordinals and would break `ch in ...`)
ASCII_FOLD = {
    "\u00e1": "a", "\u00e9": "e", "\u00ed": "i", "\u00f3": "o", "\u00fa": "u",
    "\u00fc": "u", "\u00c1": "A", "\u00c9": "E", "\u00cd": "I", "\u00d3": "O",
    "\u00da": "U", "\u00dc": "U", "\u00f1": "n", "\u00d1": "N", "\u00bf": "?", "\u00a1": "!",
    "\u2018": "'", "\u2019": "'", "\u201c": '"', "\u201d": '"', "\u2013": "-", "\u2014": "-",
}

_MSGBANK: dict = {}

# Banks with an atlas enlarged with accents (WS1).  Loaded from
# `translation/accents_manifest.json` (generated by tools/add_accents_banks.py).
_ACCENTS_BANKS: dict = {}


def accents_banks() -> set:
    """Stems with a per-bank accent patch available at runtime."""
    if not _ACCENTS_BANKS:
        man = REPO / "mod" / "translation" / "accents_manifest.json"
        banks = set()
        if man.is_file():
            try:
                data = json.loads(man.read_text(encoding="utf-8"))
                banks = {b.get("stem") for b in data.get("bancos", []) if b.get("stem")}
            except Exception:  # noqa: BLE001
                banks = set()
        _ACCENTS_BANKS["banks"] = banks
    return _ACCENTS_BANKS["banks"]


def msg_bank(stem: str):
    if stem not in _MSGBANK:
        mp = find_msg(stem)
        _MSGBANK[stem] = MsgBank(mp) if mp else None
    return _MSGBANK[stem]


def bank_dark_codes(stem: str) -> set:
    """Codes whose atlas glyph is BLACK (max channel < 128 with actual ink).

    Used to avoid picking a black duplicate of a letter when a white variant
    exists (see `load_charmap_inv`).  A glyph is considered "dark" only if it
    has ink (alpha > 0): blank/space cells (max RGB 0 but no ink) are ignored.
    """
    key = ("dark", stem)
    if key in _MSGBANK:
        return _MSGBANK[key]
    dark: set = set()
    try:
        import aif as aif_mod
        from PIL import Image
        ap = None
        for cand in (REPO / "extract" / "f0" / (stem + ".aif"),
                     REPO / "extract" / "f2" / "accents" / (stem + "_accents.aif")):
            if cand.is_file():
                ap = cand
                break
        if ap is not None:
            img = aif_mod.AifImage(ap.read_bytes(), 0)
            im = Image.frombytes("RGBA", (img.width, img.height), img.to_rgba())
            cols, rows = img.width // 32, img.height // 32
            px = im.load()
            for idx in range(cols * rows):
                r, c = divmod(idx, cols)
                mx, ink = 0, False
                for y in range(r * 32, r * 32 + 32):
                    for x in range(c * 32, c * 32 + 32):
                        p = px[x, y]
                        if p[3] > 0:
                            ink = True
                            m = max(p[0], p[1], p[2])
                            if m > mx:
                                mx = m
                if ink and mx < 128:
                    dark.add(301 + idx)
    except Exception:  # noqa: BLE001
        dark = set()
    _MSGBANK[key] = dark
    return dark


def original_segments(stem: str, sid: str):
    """Glyph segments of the ORIGINAL separated by break controls.
    Returns (list_of_code_segments, list_of_breaks)."""
    bank = msg_bank(stem)
    if bank is None:
        return [[]], []
    try:
        toks = bank.decode(int(sid))
    except Exception:
        return [[]], []
    segs, breaks = [[]], []
    for t in toks:
        if t["kind"] == "ctrl":
            if t["code"] in BREAKS:
                breaks.append(t["code"])
                segs.append([])
        elif t["kind"] == "glyph":
            segs[-1].append(t["code"])
    return segs, breaks


def find_msg(stem: Path):
    # Prefers the `.msg` ENLARGED with accents (same records/pool, unchanged
    # count -> stable signature; only the metric table changes).  Thus the
    # reflow uses the real metric of á é í ó ú ü ñ Á É Í Ó Ú Ü Ñ ¿ ¡.
    acc = REPO / "extract" / "f2" / "accents" / (stem + "_accents.msg")
    if acc.is_file():
        return acc
    for d in ("extract/f0", "extract/f0_d2"):
        p = REPO / d / (stem + ".msg")
        if p.is_file():
            return p
    return None


def atlas_cells(b: bytes) -> int:
    """Number of cells of the bank atlas (32x32) from the .msg header."""
    aw = struct.unpack_from(">I", b, 0x60)[0]
    ah = struct.unpack_from(">I", b, 0x64)[0]
    return max(1, (aw // 32) * (ah // 32))


def read_msg(path: Path):
    b = path.read_bytes()
    rec_off, pool_off, metrics_off = struct.unpack_from(">III", b, 0x20)
    count = struct.unpack_from(">I", b, 0x34)[0]
    recs = {}
    o = rec_off
    if rec_off:
        while o + 16 <= pool_off:
            A, B = struct.unpack_from(">II", b, o)
            if A == 0 and B == 0:
                break
            C, D = struct.unpack_from(">ff", b, o + 8)
            recs[A] = (C, D)
            o += 16
    return b, recs, metrics_off, count


def load_charmap_inv(path: Path, max_code: int | None = None, freq: dict | None = None,
                     dark: set | None = None):
    """charmap code->character => character->code. With max_code, ignores codes
    that do not exist in the game atlas. With `freq` (code->n), prefers the variant
    MOST USED in the original text (avoids bold/odd-size variants).

    `dark` = set of codes whose glyph is painted BLACK (max RGB < 128 with ink).
    Some atlases ship a black copy of a letter (e.g. a black `q` at code 620 in
    bank 005 used only once, vs the white `q` at 835).  The frequency heuristic
    could pick the black copy (invisible on the dark dialogue background); when a
    white alternative exists it is preferred here.  Only affects characters that
    actually have a black/white duplicate (verified: bank 005 `q`; d2_ud1_005 `+`).
    """
    raw = json.loads(path.read_text(encoding="utf-8"))
    by_char = {}
    for k, v in raw.items():
        if isinstance(v, str) and len(v) == 1:
            code = int(k)
            if max_code is not None and code > max_code:
                continue
            by_char.setdefault(v, []).append(code)
    inv = {}
    for ch, codes in by_char.items():
        if freq:
            codes = sorted(codes, key=lambda c: (-freq.get(c, 0), c))
        else:
            codes = sorted(codes)
        if dark:
            white = [c for c in codes if c not in dark]
            if white:
                codes = white
        inv[ch] = codes[0]
    return inv


def bank_stats(stem: str, cap: int = 4000):
    """(code frequency, box width) of the bank. The box width is the
    widest line (Sum advance) among all its messages: it approximates the dialogue
    box, much better than the width of each individual message."""
    key = ("stats", stem)
    if key in _MSGBANK:
        return _MSGBANK[key]
    bank = msg_bank(stem)
    fr = {}
    box = 0
    if bank is not None:
        b, recs, mo, count = read_msg(find_msg(stem))
        for i, r in enumerate(bank.records):
            if i >= cap:
                break
            try:
                toks = bank.decode(r["id"])
            except Exception:
                continue
            w = 0
            for t in toks:
                if t["kind"] == "glyph":
                    fr[t["code"]] = fr.get(t["code"], 0) + 1
                    w += advance(b, mo, t["code"])
                elif t["code"] in BREAKS:
                    box = max(box, w)
                    w = 0
            box = max(box, w)
    _MSGBANK[key] = (fr, box)
    return fr, box


def bank_code_freq(stem: str, cap: int = 4000):
    return bank_stats(stem, cap)[0]


def advance(b, metrics_off, code):
    i = code - 301 if code >= 300 else code - 1
    off = metrics_off + 2 * i
    if i < 0 or off + 1 >= len(b):
        return 0
    return b[off]


def original_lines(codes):
    lines = [[]]
    for c in codes:
        if c == LINE_BREAK:
            lines.append([])
        elif c < 0x4000 and c > 0:
            lines[-1].append(c)
    return lines


def wrap(text, inv, space, b, metrics_off, target, max_lines):
    """Returns (list_of_lines, warning). Respects explicit '\\n'."""
    # words respecting explicit line breaks
    out_lines = []
    for hard in text.split("\n"):
        words = hard.split(" ")
        cur, curw = [], 0
        for w in words:
            wc = [inv[c] for c in w if c in inv]
            ww = sum(advance(b, metrics_off, c) for c in wc)
            add = ww + (advance(b, metrics_off, space) if cur else 0)
            if cur and curw + add > target:
                out_lines.append(" ".join(cur))
                cur, curw = [w], ww
            else:
                cur.append(w)
                curw += add
        if cur:
            out_lines.append(" ".join(cur))
    warn = "" if len(out_lines) <= max_lines else "lineas %d>%d" % (len(out_lines), max_lines)
    return out_lines, warn


def _enc_code(c):
    if c < 0x80:
        return [c]
    return [(c & 0x7F) | 0x80, (c >> 7) & 0xFF]


def orig_structure(stem, sid):
    """Structure of the original: list of ('ctrl', bytes_raw) / ('glyph', [codes]).
    Controls are kept as-is (code + payload) to avoid losing
    separations/positions (credits, structured screens)."""
    bank = msg_bank(stem)
    if bank is None:
        return None
    try:
        toks = bank.decode(int(sid))
    except Exception:
        return None
    items = []
    run = []
    for t in toks:
        if t["kind"] == "ctrl":
            if run:
                items.append(("glyph", run))
                run = []
            raw = _enc_code(t["code"]) + list(t.get("payload") or [])
            items.append(("ctrl", raw))
        elif t["kind"] == "glyph":
            run.append(t["code"])
    if run:
        items.append(("glyph", run))
    return items


def build_bytes(stem, sid, lines, inv, b, metrics_off, space, break_code, use_breaks=True):
    """Emits the byte-stream: keeps the original controls and inserts the
    ES glyphs distributed among the original glyph runs."""
    items = orig_structure(stem, sid)
    glyph_runs = sum(1 for k, _ in items) if items else 0
    if not items:
        # no structure: emit lines with breaks
        out = []
        for li, line in enumerate(lines):
            if li > 0:
                out += _enc_code(break_code)
            for ch in line:
                c = space if ch == " " else (inv.get(ch) or inv.get(ASCII_FOLD.get(ch, ""), None))
                if c is None:
                    continue
                out += _enc_code(c)
        return out
    # distribute the ES lines among the glyph runs
    runs = [i for i, (k, _) in enumerate(items) if k == "glyph"]
    n = len(runs)
    # if there are MORE lines than runs, the extra ones are appended to the LAST run (with a break),
    # so as NOT to lose text.
    if n and len(lines) > n:
        merged = lines[:n - 1] + ["\n".join(lines[n - 1:])]
        lines = merged
    out = []
    li = 0
    for idx, (k, v) in enumerate(items):
        if k == "ctrl":
            out += v
        else:
            line = lines[li] if li < len(lines) else ""
            for ch in line:
                if ch == "\n":
                    out += _enc_code(break_code)
                    continue
                c = space if ch == " " else (inv.get(ch) if ch in inv else inv.get(ASCII_FOLD.get(ch, ""), None))
                if c is None:
                    continue
                out += _enc_code(c)
            li += 1
    return out


def main(argv=None):
    p = argparse.ArgumentParser()
    p.add_argument("--es", default="mod/translation/es.json")
    p.add_argument("--charmaps", default="mod/translation/charmaps")
    p.add_argument("--all-codes", default="extract/messages/all_codes.json")
    p.add_argument("--codes", default="mod/translation/es_codes.json")
    p.add_argument("--catalog", default="mod/translation/es_catalog.bin")
    p.add_argument("--fold", action="store_true")
    p.add_argument("--no-reflow", action="store_true")
    args = p.parse_args(argv)

    data_file = Path(args.es) if args.es else None
    strings = []
    files = []
    if data_file and data_file.is_file():
        files.append(data_file)
    else:
        default = REPO / "mod/translation/es.json"
        if default.is_file():
            files.append(default)
    files += sorted((REPO / "mod/translation/parts").glob("*.json")) if (REPO / "mod/translation/parts").is_dir() else []
    for f in files:
        try:
            strings += json.loads(Path(f).read_text(encoding="utf-8")).get("strings", [])
        except Exception as e:
            print("  AVISO no se pudo leer %s: %s" % (f, e))
    data = {"strings": strings}
    out, warn = {}, []

    for it in data.get("strings", []):
        stem, sid, text = it.get("stem"), str(it.get("id")), it.get("es")
        if not stem or text is None:
            continue
        cm = Path(args.charmaps) / (stem + ".json")
        mp = find_msg(stem)
        if not cm.is_file() or mp is None:
            warn.append("SIN CHARMAP/MSG %s:%s" % (stem, sid))
            continue
        b, recs, metrics_off, count = read_msg(mp)
        # Valid codes = those that have a CELL in the atlas (not just `count`).
        # If the bank has the atlas ENLARGED with accents (WS1: per-bank
        # material in `extract/f2/accents/<stem>_accents.aif` and/or an entry in
        # `translation/accents_manifest.json`), up to 300+cells are allowed
        # so the accents are NOT folded to ASCII.  Otherwise, it is limited to
        # 300+count (safe: never emit codes without a glyph).
        acc_atlas = REPO / "extract" / "f2" / "accents" / (stem + "_accents.aif")
        has_accents = acc_atlas.is_file() or stem in accents_banks()
        max_code = 300 + (atlas_cells(b) if has_accents else count)
        inv = load_charmap_inv(cm, max_code=max_code,
                              freq=bank_code_freq(stem),
                              dark=bank_dark_codes(stem))
        if args.fold:
            text = text.translate(str.maketrans("".join(ASCII_FOLD), "".join(ASCII_FOLD.values())))
        else:
            # Normalise the typographic ellipsis to three dots: some banks have a
            # dedicated `…` glyph that sits at MID-HEIGHT (Japanese style), while
            # the ASCII `.` is on the baseline (like the English original).
            text = text.replace("\u2026", "...")
        segs, breaks = original_segments(stem, sid)
        per_msg = max((sum(advance(b, metrics_off, c) for c in L) for L in segs), default=0) or 10**9
        max_lines = len(segs)
        ctx = (it.get("ctx") or "").lower()
        if max_lines > 1 and ctx == "dialogo" and not stem.startswith("d1_ud1_000A4000_005"):
            # dialogue: the box is usually wider than the text -> bank target
            target = max(per_msg, bank_stats(stem)[1])
        else:
            # menu/items/magic/system: adjust to the REAL width of the original message
            target = per_msg
        break_code = breaks[0] if breaks else LINE_BREAK
        space = inv.get(" ")

        missing = [ch for ch in text if ch not in inv and ch != " " and ch not in ASCII_FOLD]
        if args.no_reflow or max_lines <= 1:
            # Single-line original (label/list): do NOT reflow; it must fit on one.
            lines = text.split("\n")
        else:
            lines, w = wrap(text, inv, space, b, metrics_off, target, max_lines)
            if w:
                warn.append("%s:%s %s" % (stem, sid, w))

        widest = 0
        for line in lines:
            lw = 0
            for ch in line:
                if ch == " ":
                    c = space
                elif ch in inv:
                    c = inv[ch]
                elif ch in ASCII_FOLD and ASCII_FOLD[ch] in inv:
                    c = inv[ASCII_FOLD[ch]]
                else:
                    continue
                lw += advance(b, metrics_off, c)
            widest = max(widest, lw)
        if widest > target + 1:
            warn.append("%s:%s ANCHO linea=%d>%d" % (stem, sid, widest, target))
        if missing:
            warn.append("%s:%s sin glifo: %s" % (stem, sid, "".join(sorted(set(missing)))))
        # (REVERTED temporarily) emission as u16 codes, without preserving controls.
        codes = []
        for li, line in enumerate(lines):
            if li > 0:
                codes.append(break_code)
            for ch in line:
                if ch == "\n":
                    codes.append(break_code)
                    continue
                if ch == " ":
                    c = space
                elif ch in inv:
                    c = inv[ch]
                elif ch in ASCII_FOLD and ASCII_FOLD[ch] in inv:
                    c = inv[ASCII_FOLD[ch]]
                else:
                    continue
                codes.append(c)
        out.setdefault(stem, {})[sid] = codes

    Path(args.codes).write_text(json.dumps(out, ensure_ascii=False), encoding="utf-8")
    n = sum(len(v) for v in out.values())
    print("escrito %s: %d cadenas en %d bancos" % (args.codes, n, len(out)))
    rc = gen.main(["--es-codes", args.codes, "--out", args.catalog])
    for w in warn:
        print("  AVISO", w)
    return rc


if __name__ == "__main__":
    raise SystemExit(main())

import json

# Build the EN -> ES map for the runtime MapName table rewrite (option D).
# ES is folded to ASCII (the banner's serif font has no accented glyphs).

FOLD = {
    "á": "a", "é": "e", "í": "i", "ó": "o", "ú": "u", "ü": "u", "ñ": "n",
    "Á": "A", "É": "E", "Í": "I", "Ó": "O", "Ú": "U", "Ü": "U", "Ñ": "N",
    "¿": "?", "¡": "!", "…": "...", "\u2013": "-", "\u2014": "-", "’": "'",
    "“": '"', "”": '"', "«": '"', "»": '"',
}


def fold(s):
    return "".join(FOLD.get(c, c) for c in s)


def esc(s):
    out = []
    for c in s:
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif 32 <= ord(c) < 127:
            out.append(c)
        else:
            out.append("\\x%02x" % (ord(c) & 0xFF))
    return "".join(out)


pairs = {}
for f in ["mod/translation/parts/menu_names.json",
          "mod/translation/parts/dialog_d1_ud1_000A4000_005.json"]:
    try:
        d = json.load(open(f, encoding="utf-8"))
    except Exception:
        continue
    for e in (d.get("strings", d) if isinstance(d, dict) else d):
        if not isinstance(e, dict):
            continue
        en, es, i = e.get("en"), e.get("es"), str(e.get("id"))
        if not en or not es:
            continue
        if f.endswith("menu_names.json") or i.startswith(("100", "104", "105", "78000")):
            pairs.setdefault(en.strip(), fold(es.strip()))

lines = [
    "// zone_names.h -- EN -> ES map for the ZONE-NAME banner (option D).",
    "//",
    "// The zone-title banner reads the .exe's MapName table (guest ~0x82A01A58)",
    "// as ASCII (see docs/re/zone-banner.md).  This table rewrites those names in",
    "// memory at startup (no asset is touched).  ES is folded to ASCII because the",
    "// banner's serif font has no accented glyphs.",
    "//",
    "// GENERATED by tools/gen_zone_names.py -- do not edit by hand.",
    "",
    "#pragma once",
    "",
    "namespace iu::translation {",
    "",
    "struct ZoneNamePair { const char* en; const char* es; };",
    "",
    "inline const ZoneNamePair* ZoneNamePairs(int& n) {",
    "  static const ZoneNamePair k[] = {",
]
for en in sorted(pairs):
    lines.append('      {"%s", "%s"},' % (esc(en), esc(pairs[en])))
lines += [
    "  };",
    "  n = int(sizeof(k) / sizeof(k[0]));",
    "  return k;",
    "}",
    "",
    "}  // namespace iu::translation",
    "",
]
open("mod/recomp/zone_names.h", "w", encoding="utf-8").write("\n".join(lines))
print("zone_names.h:", len(pairs), "pares")
